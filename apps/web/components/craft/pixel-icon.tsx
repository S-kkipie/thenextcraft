export type PixelIconName = keyof typeof GRIDS;

/** Todos los nombres disponibles — útil para una galería o un test. */
export const PIXEL_ICONS = Object.keys(GRIDS) as PixelIconName[];

export function PixelIcon({
  name,
  size = 14,
  className,
  title,
}: {
  name: PixelIconName;
  /** Lado en px. Múltiplos de 10 caen exactos en la rejilla. */
  size?: number;
  className?: string;
  /** Si se pasa, el icono es semántico; si no, es decorativo y va oculto. */
  title?: string;
}) {
  const grid = GRIDS[name];
  const rects: React.ReactElement[] = [];

  // Se agrupan los píxeles encendidos contiguos de cada fila en un solo <rect>:
  // ~10 nodos por icono en vez de ~50.
  for (let y = 0; y < grid.length; y++) {
    const row = grid[y];
    let x = 0;
    while (x < row.length) {
      if (row[x] !== "#") {
        x++;
        continue;
      }
      let run = 0;
      while (x + run < row.length && row[x + run] === "#") run++;
      rects.push(
        <rect key={`${y}-${x}`} x={x} y={y} width={run} height={1} />,
      );
      x += run;
    }
  }

  return (
    <svg
      viewBox={`0 0 ${G} ${G}`}
      width={size}
      height={size}
      fill="currentColor"
      shapeRendering="crispEdges"
      role={title ? "img" : undefined}
      aria-label={title}
      aria-hidden={title ? undefined : true}
      focusable="false"
      className={cn("inline-block shrink-0 align-[-0.14em]", className)}
    >
      {title && <title>{title}</title>}
      {rects}
    </svg>
  );
}
